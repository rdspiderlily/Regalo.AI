# backend/app/services/gift_service.py
import json
from app.core.ai_client import generate_gift_ideas
from app.utils.prompt_formatter import format_gift_prompt
from app.schemas.gift_schema import GiftIdea

async def get_gift_ideas(recipient: str, interests: str, budget: str):
    prompt = format_gift_prompt(recipient, interests, budget)
    raw_output = await generate_gift_ideas(prompt)

    # Normalize raw_output to a JSON string
    if isinstance(raw_output, list):
        # Check if list contains dicts
        if all(isinstance(i, dict) for i in raw_output):
            raw_output_str = json.dumps(raw_output)
        else:
            # Assume list of strings
            raw_output_str = "\n".join(str(i) for i in raw_output)
    else:
        raw_output_str = str(raw_output)

    # Remove triple backticks if present
    raw_output_str = raw_output_str.strip("`").replace("json", "").strip()

    ideas = []
    try:
        data = json.loads(raw_output_str)
        if isinstance(data, dict):
            data = [data]

        for item in data:
            ideas.append(GiftIdea(
                title=str(item.get("title", "AI Suggestion")),
                description=str(item.get("description", "No description")),
                reason=str(item.get("reason", "Generated by AI")),
                budget=str(item.get("budget", budget))
            ))

    except (json.JSONDecodeError, TypeError, ValueError):
        # fallback single idea
        ideas.append(GiftIdea(
            title="AI Suggestion",
            description=raw_output_str,
            reason="Generated by AI",
            budget=budget
        ))

    return ideas





